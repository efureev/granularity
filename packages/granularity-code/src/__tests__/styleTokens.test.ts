import { defineStyleTokensGate } from '@feugene/granularity-test-kit/gates'

/**
 * Кегли, радиусы и длительности объявлены токенами и ровно поэтому выглядят
 * настраиваемыми. Пиксельный литерал или утилита `text-sm` этого обещания не
 * держат: тема их не видит.
 */
/**
 * `requireTokenUsage: false` — у пакета нет анимации.
 *
 * Проверка «хоть один `--gr-duration-*` употреблён» защищает от пакета, который
 * анимирует литералами. Здесь анимации нет вовсе: код показывают, правят и
 * сравнивают, и двигаться в нём нечему. Завести переход ради зелёного гейта
 * значило бы подогнать код под проверку, а не наоборот. Запрет литералов при
 * этом остаётся в силе — он и есть суть гейта.
 */
defineStyleTokensGate({ requirePairedLeading: true, requireTokenUsage: false })
