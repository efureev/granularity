import { plainLines, type GrCodeLine } from './palette'
import { tokenizeJson } from './tokenizeJson'

/**
 * Встроенный разбор — один на все три компонента.
 *
 * Блок, серверная разметка редактора и мост в декорации CodeMirror показывают
 * один и тот же текст на одной и той же странице. Разойдись у них разбор —
 * разошёлся бы и цвет, причём молча: сравнить их между собой нечем, кроме глаз.
 * Поэтому источник строк ровно один, а компоненты выбирают только форму вызова.
 */

/**
 * Разбор **одной строки**.
 *
 * Единица именно строка, а не текст целиком, и это не мелочь: на ней держится
 * мост в CodeMirror. Тот декорирует только видимое окно, и позволяет ему это
 * ровно строчная локальность разбора — JSON переноса внутри токена не содержит
 * (в строковом литерале он экранирован), поэтому строку можно разобрать, ничего
 * не зная о соседях.
 *
 * Язык, которому нужен контекст соседних строк (блочный комментарий,
 * многострочный литерал), сюда не поместится — ему нужна грамматика CodeMirror.
 * Это граница возможностей, а не недоделка.
 */
export function builtInLine(text: string, language: string): GrCodeLine {
  return language === 'json' ? tokenizeJson(text) : [{ text, role: 'plain' }]
}

/**
 * Разбор текста целиком, построчно.
 *
 * Номер строки — CSS-счётчик, а счётчику нужен элемент на строку, поэтому и
 * блоку, и серверной разметке редактора нужен именно массив строк.
 */
export function builtInLines(code: string, language: string): GrCodeLine[] {
  if (language !== 'json')
    return plainLines(code)

  return code.split('\n').map(row => builtInLine(row, language))
}

/**
 * Построчный разбор для языка — или `null`, если встроенного разбора нет.
 *
 * `null` вместо «токенизатора, который всё красит в `plain`»: мосту в CodeMirror
 * это позволяет не ставить плагин вовсе, а не гонять разбор по видимым строкам
 * ради пустого результата.
 */
export function builtInLineTokenizer(language: string): ((text: string) => GrCodeLine) | null {
  return language === 'json' ? tokenizeJson : null
}
