/**
 * Палитра подсветки — одна на пакет, три производителя.
 *
 * Ядро красило шестью ролями, и этого хватало: блок показывал JSON. Пакет
 * показывает любой язык, и шести мало — TypeScript без `keyword` и `comment`
 * выглядит невнятной простынёй.
 *
 * Производителей три и все сводятся сюда: встроенный `tokenizeJson` (JSON и
 * текст, ноль зависимостей), Shiki у потребителя (`fromShiki`) и Lezer внутри
 * CodeMirror (`fromLezer`). Код на одной странице обязан выглядеть одинаково
 * независимо от того, каким из трёх компонентов показан, — ради этого роли и
 * общие.
 */

/**
 * Роль токена. Одиннадцать — не больше и не меньше.
 *
 * Больше значило бы завести различие, которого нет у встроенного токенизатора:
 * роль, доступная одному производителю из трёх, разъедет вид одного и того же
 * кода между блоком и диффом. Меньше — вернуть потолок, ради снятия которого
 * компонент и переехал из ядра.
 */
export const GR_CODE_ROLES = [
  /** Имя поля объекта: строка, за которой идёт двоеточие. */
  'key',
  'string',
  'number',
  /** `true`, `false`, `null` и их аналоги. */
  'literal',
  /** Скобки, запятые, двоеточия, операторы. */
  'punctuation',
  /** Ключевое слово языка: `if`, `return`, `const`. */
  'keyword',
  'comment',
  /** Имя типа, класса, интерфейса. */
  'type',
  /** Имя функции в объявлении или вызове. */
  'function',
  /** Имя переменной или параметра. */
  'variable',
  /** Пробелы, переносы и всё, что не опознано. */
  'plain',
] as const

export type GrCodeRole = typeof GR_CODE_ROLES[number]

const ROLE_SET = new Set<string>(GR_CODE_ROLES)

/** Роль ли это. Нужен производителям: чужое имя обязано осесть в `plain`, а не протечь наружу. */
export function isGrCodeRole(value: unknown): value is GrCodeRole {
  return typeof value === 'string' && ROLE_SET.has(value)
}

/** Один разобранный кусок строки. */
export interface GrCodeToken {
  text: string
  role: GrCodeRole
}

/** Одна строка кода, разобранная на роли. */
export type GrCodeLine = readonly GrCodeToken[]

/**
 * Всё, что компонент требует от подсветки.
 *
 * Форма взята с `GranularityI18nAdapter` ядра и по той же причине: пакет
 * объявляет **потребность**, а не поставщика. Приложение подключает Shiki,
 * Prism, серверную подсветку или готовые токены из API — пакету всё равно,
 * и `shiki` не появляется ни в его зависимостях, ни в импортах типов.
 *
 * Промис в возвращаемом типе — ради воркера и серверной подсветки. Встроенный
 * разбор и адаптер к Shiki синхронны.
 */
export type GrCodeTokenizer = (
  code: string,
  language: string,
) => GrCodeLine[] | Promise<GrCodeLine[]>

/**
 * Разбивка текста на строки без подсветки: одна `plain`-роль на строку.
 *
 * Это и режим «языка нет», и первый кадр перед ответом асинхронного
 * токенизатора. Пустая строка остаётся строкой с пустым токеном, иначе номера
 * строк разъедутся с содержимым.
 */
export function plainLines(code: string): GrCodeLine[] {
  return code.split('\n').map(text => [{ text, role: 'plain' as const }])
}
