/**
 * Инстанс `@feugene/fint-i18n` для `provide` — в форме опций монтирования.
 *
 * Ключ — глобальный символ, а не импортированная константа: пакеты
 * дизайн-системы ищут инстанс ровно им, чтобы не делать `fint-i18n`
 * обязательной рантайм-зависимостью. Тест обязан класть его туда же, иначе
 * компонент останется на fallback-текстах и проверка перевода зазеленеет,
 * ничего не проверив.
 *
 * Возвращается `{ provide }`, а не `{ global: { provide } }` — как у
 * `granularityGlobal()` ядра, и по той же причине: две обёртки, каждая со
 * своим `global`, не складываются. При `{ ...a(), ...b() }` поздний `global`
 * молча съедает ранний, и один из двух наборов исчезает без ошибки. С этой
 * формой они соединяются: `global: { provide: { ...granularityGlobal().provide,
 * ...fintI18nGlobal(i18n).provide } }`.
 */
export function fintI18nGlobal(i18n: unknown): { provide: Record<symbol, unknown> } {
  return { provide: { [Symbol.for('FintI18n')]: i18n } }
}
