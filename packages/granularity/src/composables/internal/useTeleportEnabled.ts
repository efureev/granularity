import { onMounted, readonly, ref, type Ref } from 'vue'

/**
 * Можно ли телепортировать содержимое прямо сейчас.
 *
 * Возвращает `false` на сервере И на первом клиентском рендере, `true` — сразу
 * после монтирования. Использовать так:
 *
 * ```vue
 * <teleport to="body" :disabled="!teleportEnabled">…</teleport>
 * ```
 *
 * ## Зачем, если есть `typeof window !== 'undefined'`
 *
 * Проверка окружения выглядит достаточной, но именно она и ломала гидрацию.
 * `isClient` вычисляется в `setup`, поэтому получалось так:
 *
 * - сервер: `window` нет → телепорт выключен → содержимое остаётся НА МЕСТЕ
 *   (`:disabled` означает «рендерить на месте», а не «не рендерить»);
 * - клиент, первый рендер: `window` есть → телепорт включён → содержимое сразу
 *   уезжает в `body`.
 *
 * Структуры не совпадают, Vue сообщает `Hydration node mismatch`. В лучшем
 * случае это лишний варнинг и осиротевшая копия панели в DOM; в худшем —
 * панель «прилипает» к контейнеру приложения и пишет в него свои стили
 * (`position: fixed` + `display: none` у закрытой панели), после чего страница
 * исчезает целиком.
 *
 * Флаг, поднимаемый в `onMounted`, снимает проблему по построению: **первый**
 * клиентский рендер повторяет серверный, а телепорт включается уже после
 * гидрации. Для компонентов без SSR это ничего не меняет: панели закрыты
 * (`v-show`/`v-if`), а `onMounted` срабатывает в том же тике.
 *
 * Стенд, на котором это воспроизводится и проверяется, — `apps/playground-ssr`.
 */
export function useTeleportEnabled(): Readonly<Ref<boolean>> {
  const enabled = ref(false)

  onMounted(() => {
    enabled.value = true
  })

  return readonly(enabled)
}
