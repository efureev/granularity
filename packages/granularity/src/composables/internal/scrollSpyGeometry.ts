/**
 * Арифметика положения чтения: чистые функции без DOM и без реактивности.
 *
 * Вынесена отдельно по той же причине, что и геометрия перестановки в
 * `dragSortGeometry.ts`: ошибка здесь проявляется не исключением, а
 * «подсветился не тот раздел», и поймать это можно только тестом на числах. В
 * jsdom проверить нечем вовсе — там нет ни прокрутки, ни раскладки.
 *
 * Композабл `useScrollSpy` сводит `DOMRect` к числам и зовёт эти функции; что
 * значит активный раздел для разметки, решает уже компонент.
 */

/** Верх раздела в координатах вьюпорта. */
export interface ScrollSpyRect {
  id: string
  top: number
}

/**
 * Допуск линии активации.
 *
 * `GrAffix` от эпсилона отказался осознанно — там рядом стоит CSS, у которого
 * его нет, и расхождение с ним было бы дороже дребезга. Здесь параллельного
 * источника истины нет: единственный потребитель числа — этот модуль. А повод
 * конкретный: прокрутка ставится так, чтобы верх раздела совпал с линией, но
 * браузеры округляют смещение, и приземление на `line + 0.5` дало бы «кликнул
 * третий раздел — подсветился второй».
 */
const SNAP_EPSILON = 2

/**
 * Какой раздел читают сейчас.
 *
 * Правило — «последний, чей верх выше линии», а не «самый видимый». Максимум
 * доли пересечения ошибается двумя способами: длинный раздел выигрывает у
 * короткого независимо от того, что читают, и подсветка отскакивает назад,
 * когда следующий раздел только показался снизу. Здесь ответ — заголовок,
 * ближайший сверху к линии чтения.
 *
 * Порядок массива на ответ не влияет: выбор идёт по геометрии. Это снимает
 * класс дефектов, где объявленный список разошёлся с порядком разделов на
 * странице — подсветку в таком случае невозможно отладить.
 *
 * `atEnd` побеждает правило линии, и без него последний раздел недостижим:
 * раздел короче остатка скроллпорта никогда не доводит свой верх до линии,
 * потому что прокрутка кончается раньше.
 */
export function activeSectionId(
  rects: readonly ScrollSpyRect[],
  line: number,
  atEnd: boolean,
): string | null {
  // Пустой вход — это сразу три случая: пустой список, ни одного элемента в
  // DOM, наблюдение выключено. Все три означают «сказать нечего».
  if (rects.length === 0)
    return null

  let best: ScrollSpyRect | null = null

  for (const rect of rects) {
    if (!atEnd && rect.top - line > SNAP_EPSILON)
      continue

    if (best === null || rect.top > best.top)
      best = rect
  }

  return best?.id ?? null
}

/**
 * `rootMargin` наблюдателя: верх корня поджимается на отступ, и тогда его край
 * совпадает с линией активации.
 *
 * Единицы только `px`: `rootMargin` произвольных длин не принимает, поэтому
 * отступ приходит сюда уже замеренным.
 */
export function scrollSpyRootMargin(offsetPx: number): string {
  const px = Number.isFinite(offsetPx) ? Math.max(0, Math.round(offsetPx)) : 0
  const negative = -px
  // Число выносится в переменную, чтобы литерал остался одним токеном: гейт
  // safelist разбирает шаблонные строки по пробелам, а обломок вида `-${px}px`
  // принимает за утилиту UnoCSS — которой он, по совпадению, и оказывается.
  const inset = `${negative}px`
  const zero = '0px'

  return [inset, zero, zero, zero].join(' ')
}

/**
 * Куда прокрутить скроллпорт, чтобы верх раздела встал на линию активации.
 *
 * Своя арифметика вместо `scrollIntoView` — по трём независимым причинам:
 * тот двигает всех предков (у карусели это стоило прыжка страницы на каждом
 * шаге автопрокрутки), не умеет наш отступ, и в jsdom отсутствует вовсе, то
 * есть клик стал бы непроверяемым.
 */
export function scrollSpyTargetTop(
  scrollTop: number,
  sectionTop: number,
  portTop: number,
  offset: number,
  maxScrollTop: number,
): number {
  const upper = Math.max(0, Number.isFinite(maxScrollTop) ? maxScrollTop : 0)
  const target = scrollTop + (sectionTop - portTop) - Math.max(0, offset)

  return Math.min(upper, Math.max(0, target))
}

/**
 * Прокручивается ли предок.
 *
 * Читается вычисленный `overflow-y`, а не объявленный: при
 * `overflow-x: hidden; overflow-y: visible` спецификация превращает вычисленный
 * `overflow-y` в `auto`, то есть предок действительно становится скроллпортом.
 */
export function isScrollableOverflow(overflowY: string): boolean {
  return overflowY === 'auto' || overflowY === 'scroll' || overflowY === 'overlay'
}

/**
 * Доехали ли до дна.
 *
 * `maxScrollTop > 1` — обязательное условие, а не перестраховка: содержимое
 * короче скроллпорта даёт «дно» на нулевой прокрутке, и правило `atEnd`
 * подсветило бы последний раздел на странице, где позиции чтения нет вовсе.
 */
export function isScrolledToEnd(scrollTop: number, maxScrollTop: number): boolean {
  return maxScrollTop > 1 && scrollTop >= maxScrollTop - SNAP_EPSILON
}
