import { defineEnvGuardGate } from '@feugene/granularity-test-kit/gates'

/**
 * Дев-гард — общей фабрикой: правило одно на все пакеты, а раньше жило только
 * здесь. Из-за этого четыре `console.warn` в ядре и в графиках кричали в проде
 * у потребителя: ни одного условия вокруг них не было, а гейт проверял только
 * то, что написанные руками условия не появляются.
 *
 * `guardValue` передаётся отсюда, а не читается фабрикой: подстановка `define`
 * текстовая и работает только там, где файл проходит через трансформ пакета.
 * Фабрика приезжает собранной из `node_modules`, и имя в ней никто не заменит.
 */
defineEnvGuardGate({
  guardValue: __GR_DEV__,
  minFiles: 300,
  minGuards: 15,
  allowUnguarded: {
    // Предупреждение живёт в модульной функции, а гард — на стороне
    // единственного вызова (`if (__GR_DEV__) warnUnsupportedSize(…)`), то есть
    // ниже по файлу. Форма осознанная: рядом с вызовом стоит и дедуп.
    'components/GrConfigProvider/context.ts': 'гард на стороне единственного вызова',
  },
})
