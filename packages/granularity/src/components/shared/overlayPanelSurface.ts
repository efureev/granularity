/**
 * Общая поверхность всплывающей панели: радиус, рамка, фон, тень.
 *
 * До выноса шесть этих утилит были скопированы пять раз — у поповера,
 * выпадающего меню и трёх списков выбора. Расходились бы молча: разница в одном
 * токене видна только рядом с эталоном, а эталоны у компонентов свои.
 *
 * Фон — `--gr-popover`, и это не выбор из двух равных. Описание токена в
 * `tokens/themes/*.json` — «Фон popover-, dropdown- и overlay-поверхностей», то
 * есть он заведён ровно под этот случай; `--gr-card` — фон карточки. Четверо из
 * пяти брали карточный, и значения совпадали, поэтому расхождение не
 * проявлялось. Проявилось бы у первого, кто перекрасит `--gr-popover`, чтобы
 * отличать всплывающие поверхности от карточек.
 *
 * Всё, что специфично для компонента, — поле, потолок ширины, `overflow` — он
 * дописывает сам: это уже не поверхность, а его собственная раскладка.
 *
 * Модуль безадресный: в `dist` он уезжает в общий чанк, который пресет не
 * сканирует, поэтому каждый потребитель объявляет эти классы в своём `safelist.ts`.
 */
export const overlayPanelSurfaceClass = 'rounded-[var(--gr-radius-xl)] border border-[var(--gr-brd)] bg-[var(--gr-popover)] text-[var(--gr-popover-fg)] shadow-[var(--gr-shadow-2)]'
