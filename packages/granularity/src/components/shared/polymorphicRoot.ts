/**
 * Компонент с полиморфным корнем (`as`) обязан различать две вещи, которые
 * легко спутать: какой тег попросили и что этот тег умеет.
 *
 * `as` называет **тег**, а не поведение. Интерактивность даёт то, что попадает
 * в таб-порядок само: `<button>` и `<a>` **со** ссылкой. Безымянный `<a>` не
 * фокусируется и роли ссылки не имеет, поэтому одного тега мало.
 *
 * Компонент-ссылка (`RouterLink`, `Link` от Inertia) сюда не попадает: он
 * рендерит `<a>` сам, но узнать это до рендера нельзя — вызывающая сторона
 * считает его интерактивным по типу значения, а не по имени тега.
 *
 * Цена ошибки — кольцо фокуса на `<section>`: обещание клавиатуры, которое
 * некому выполнить. Правило успело разойтись по четырём компонентам копиями,
 * поэтому живёт здесь.
 */
export function isFocusableTag(tag: string, hasHref: boolean): boolean {
  return tag === 'button' || (tag === 'a' && hasHref)
}
