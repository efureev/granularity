/**
 * Крупный шаг клавиатуры: `PageUp` и `PageDown`.
 *
 * Десять обычных шагов либо десятая часть диапазона — что крупнее. Правило
 * одно на слайдер и числовое поле: у обоих `PageUp` обязан двигать значение
 * заметно, но кратно шагу, иначе значение уедет мимо сетки.
 *
 * Границы необязательны, потому что у поля их может не быть вовсе — без них
 * диапазона не существует и остаются те же десять шагов. Компонент, у которого
 * границы обязательны, но могут выродиться (`max <= min` у слайдера),
 * подставляет сюда уже нормализованный размах: так обе трактовки вырожденного
 * случая сохраняются без ветвления внутри формулы.
 */
export function bigStep(step: number, min?: number, max?: number): number {
  const base = step * 10
  if (min === undefined || max === undefined) return base

  const span = max - min
  const tenth = Math.round((span / 10) / step) * step

  return Math.max(base, tenth || step)
}
