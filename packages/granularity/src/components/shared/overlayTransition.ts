/**
 * Набор перехода всплывающей панели.
 *
 * Пять панелей — выпадающее меню, поповер, списки выбора — появляются
 * одинаково, и до выноса держали этот набор литералами в своих шаблонах:
 * шесть строк, повторённых дословно пять раз. Разъезжались они молча, потому
 * что визуально расхождение в одной фазе заметно только рядом с эталоном.
 *
 * Форма — объект по фазам, как `overlayTransition`/`panelTransition` у
 * `GrModal`: так набор биндится в `<transition>` по одному имени на фазу, не
 * превращаясь в «мешок токенов».
 *
 * Классы набора лежат здесь целыми литералами, и granum извлекает их сам: на
 * сборке пакета экстрактор обходит все чанки компонента, общий чанк с этим
 * модулем тоже. Объявлять набор в safelist потребителя не нужно. Два правила:
 *
 * 1. **Набор переезжает сюда только с двумя и более потребителями.**
 *    Единственный потребитель ничего не выигрывает: его литералы и так лежат в
 *    его `.vue`, а общий модуль ради одного — лишняя ступень. Поэтому здесь нет
 *    фейда `GrTooltip`.
 * 2. **Класс набора — только целый литерал.** Собранный из частей класс
 *    экстрактор не видит, и его пришлось бы объявлять в safelist каждого
 *    потребителя.
 *
 * Отсюда же следствие: **один набор — один файл**. Экстрактор видит модуль
 * целиком, и второй набор, положенный сюда же, приехал бы в CSS каждого
 * потребителя первого — `GrPopover` понёс бы классы, которых не рендерит.
 */
export const panelPopTransition = {
  enter: 'transition ease-[var(--gr-ease-out)] duration-[var(--gr-duration-fast)]',
  enterFrom: 'transform opacity-0 scale-95',
  enterTo: 'transform opacity-100 scale-100',
  leave: 'transition ease-[var(--gr-ease-in)] duration-[var(--gr-duration-fast)]',
  leaveFrom: 'transform opacity-100 scale-100',
  leaveTo: 'transform opacity-0 scale-95',
} as const
