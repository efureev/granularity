/**
 * Набор перехода всплывающей панели.
 *
 * Пять панелей — выпадающее меню, поповер, списки выбора — появляются
 * одинаково, и до выноса держали этот набор литералами в своих шаблонах:
 * шесть строк, повторённых дословно пять раз. Разъезжались они молча, потому
 * что визуально расхождение в одной фазе заметно только рядом с эталоном.
 *
 * Форма — объект по фазам, как `overlayTransition`/`panelTransition` у
 * `GrModal`: так набор биндится в `<transition>` по одному имени на фазу и
 * разворачивается в safelist одним вызовом, не превращаясь в «мешок токенов».
 *
 * Два правила, оба следуют из того, что модуль безадресный (в `dist` он лежит
 * в общем чанке, который пресет не сканирует):
 *
 * 1. **Каждый потребитель обязан объявить эти классы в своём `safelist.ts`** —
 *    через `flattenTransitionTokens`. Гейт `src/__tests__/safelist.test.ts`
 *    проверяет это обходом импортов; забывшего он назовёт поимённо.
 * 2. **Один пресет — один файл.** Второй набор, положенный сюда же, обложил бы
 *    налогом потребителей первого: safelist считается по модулю целиком, и
 *    `GrDropdown` понёс бы классы, которых не рендерит.
 *
 * Набор с единственным потребителем сюда не переезжает вовсе — литералы в его
 * `.vue` находит скан, и это дешевле. Поэтому здесь нет фейда `GrTooltip`.
 */
export const panelPopTransition = {
  enter: 'transition ease-[var(--gr-ease-out)] duration-[var(--gr-duration-fast)]',
  enterFrom: 'transform opacity-0 scale-95',
  enterTo: 'transform opacity-100 scale-100',
  leave: 'transition ease-[var(--gr-ease-in)] duration-[var(--gr-duration-fast)]',
  leaveFrom: 'transform opacity-100 scale-100',
  leaveTo: 'transform opacity-0 scale-95',
} as const
