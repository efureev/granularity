/**
 * Классы `GrValue`.
 *
 * Оформление аффиксов задаётся токенами, а не решением компонента. Раньше это
 * решение было зашито: префикс набирался как число, суффикс — как единица
 * измерения. Для `$14,99` и `42 %` правило верное, но доменное: рубль пишут
 * справа (`1 284 500 ₽`), и в роли суффикса он получал вид подписи.
 *
 * Дефолты сохраняют прежний вид, поэтому потребителю, которого он устраивал,
 * менять нечего.
 */

/**
 * Величина набирается кеглем и цветом того места, где стоит: своей шкалы у
 * примитива нет. `tabular-nums` держит ширину строки, когда число меняется.
 */
export const valueRootClass = 'inline-flex items-baseline tabular-nums'

/**
 * Префикс — часть записи величины: по умолчанию её цвет, её кегль, вплотную.
 * `inherit` в фолбэке и делает «по умолчанию» наследованием, а не копией: тон
 * задаётся один раз на родителе и доезжает сюда сам.
 */
export const valuePrefixClass = [
  'leading-none',
  'text-[var(--gr-value-prefix-color,inherit)]',
  'text-[length:var(--gr-value-prefix-size,inherit)]',
  'me-[var(--gr-value-prefix-gap,0)]',
].join(' ')

/**
 * Суффикс по умолчанию — единица измерения: приглушён, на ступень мельче и
 * отбит от числа.
 *
 * `leading-none` обязателен вместе с уменьшенным кеглем: межстрочный
 * наследуется от величины и рассчитан на её размер, а выровненная по базовой
 * линии приписка со своим меньшим кеглем растягивала бы им всю строку.
 *
 * Логический `me`/`ms` вместо `mr`/`ml`: в RTL отбивка обязана встать с другой
 * стороны, иначе суффикс прилипнет к числу.
 */
export const valueSuffixClass = [
  'leading-none',
  'text-[var(--gr-value-suffix-color,var(--gr-muted-fg))]',
  'text-[length:var(--gr-value-suffix-size,0.85em)]',
  'ms-[var(--gr-value-suffix-gap,0.25rem)]',
].join(' ')
