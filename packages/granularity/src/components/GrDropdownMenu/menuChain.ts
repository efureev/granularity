import type { InjectionKey, Ref } from 'vue'

/**
 * Связь панели меню с её подменю.
 *
 * Уровни меню — независимые слои в портале: панель подменю лежит в DOM рядом с
 * родительской, а не внутри неё. Поэтому всё, что должно решаться на всю
 * цепочку сразу, приходится передавать явно: DOM-родства между уровнями нет.
 */
export interface GrMenuChainContext {
  /**
   * Закрыть меню целиком, с корня. Нужен подменю: `closeOnContentClick`
   * родителя ловит клики в своей панели, а выбор произошёл в чужой.
   */
  closeRoot: () => void
  /** Закрывать ли меню по выбору пункта — решение корня. */
  closeOnSelect: () => boolean
  /** Глубина панели: 0 — корневая. */
  level: number
  /**
   * Раскрыта ли панель этого уровня. Подменю обязано следить за ней: панель
   * родителя скрывается через `v-show`, компонент подменю остаётся смонтирован,
   * и его собственная панель осталась бы висеть в портале одна.
   */
  open: Ref<boolean>
  /**
   * Ключ раскрытого подменю этого уровня. Сосед, увидев чужой ключ, закрывается
   * сам: у клавиатуры `mouseleave` не бывает, и без этого панель осталась бы
   * висеть после ухода фокуса на соседний пункт.
   */
  active: Ref<symbol | null>
  /**
   * Курсор идёт коридором к уже раскрытой панели. Пока это так, соседние пункты
   * своё подменю не открывают — иначе диагональный проход к подменю уводит
   * пользователя в чужое.
   */
  travelling: Ref<boolean>
}

export const GR_MENU_CHAIN_KEY: InjectionKey<GrMenuChainContext> = Symbol.for('@feugene/granularity/menu-chain')
