import { windEngine } from '@feugene/granum-engine-wind'

/**
 * Конфиг для `granum doctor` на самом пакете.
 *
 * Провайдеры перечислены именами пакетов: CLI найдёт `dist/granum.manifest.json`
 * каждого через `exports`, то есть проверит то, что отгружается, а не исходники.
 * Донор обязателен в списке — без него не развернётся замыкание графа, и
 * зависимости компонентов останутся неудовлетворёнными.
 *
 * Селекция ограничена своими компонентами: компоненты ядра проверяет его
 * собственный `doctor`. Замыкание всё равно подтянет те из них, от которых
 * компоненты пакета зависят, — именно это и надо проверить.
 *
 * `@feugene/granularity-chrono` в списке нет намеренно, хотя он и объявлен
 * optional peer: `GrSchemaForm` не зависит от пикеров даты — их набор
 * потребитель подключает явно (`docs/renderers.md`). Провайдер, который ничего
 * не даёт сборке, доктор показывает как `unused-provider`, и он прав.
 *
 * Движок тот же, которым пакет собран: на другом словаре доктор показал бы
 * расхождение диалектов вместо состояния пакета.
 */
export default {
  providers: [
    '@feugene/granularity',
    '@feugene/granularity-forms-schema',
  ],
  engine: windEngine(),
  components: [{ provider: '@feugene/granularity-forms-schema', names: 'all' }],
}
