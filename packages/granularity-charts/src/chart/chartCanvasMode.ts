import type { NormalizedSeries } from './chartModel'

/**
 * Выбор рендерера: SVG или холст.
 *
 * Граница проведена по замеру, а не по интуиции. Цена SVG растёт линейно с
 * числом **нарисованных вершин** — около 0,8 мс на ряд из 2400 при ширине
 * 1200px, — и на двадцати рядах кадр перестаёт помещаться в бюджет:
 *
 * | рядов | SVG | холст |
 * | --- | --- | --- |
 * | 1 | 1,1 мс | 0,4 мс |
 * | 8 | 6,7 мс | 0,6 мс |
 * | 20 | 16,3 мс | 1,7 мс |
 *
 * **Считать надо вершины, а не точки.** Прореживание режет каждый ряд по
 * отдельности, поэтому суммарное число точек о цене не говорит ничего: один
 * ряд в сто тысяч точек рисуется как 2400 вершин и стоит миллисекунду, а
 * двадцать рядов по 2400 — те же 48 000 точек — стоят шестнадцати.
 */

/** Половина бюджета кадра по замеру: 24 000 вершин ≈ 8 мс в SVG. */
export const GR_CHART_CANVAS_THRESHOLD = 24_000

/**
 * Марки перестают читаться задолго до того, как начинает болеть отрисовка, и
 * гасятся своим числом. Раньше их гасил `canvasThreshold` — при том, что
 * никакого холста в пакете не было.
 */
export const GR_CHART_MARKERS_LIMIT = 2000

/** Сколько вершин уйдёт в рисунок: ряды уже прорежены, считаем их как есть. */
export function drawnVertices(series: readonly NormalizedSeries[]): number {
  return series.reduce((total, item) => total + item.points.length, 0)
}

/** Порог `0` и меньше выключает холст совсем: так его отключает потребитель. */
export function shouldUseCanvas(series: readonly NormalizedSeries[], threshold: number): boolean {
  return threshold > 0 && drawnVertices(series) > threshold
}
