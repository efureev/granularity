/**
 * Строки интерфейса пакета — три локали, как требует конвенция репозитория.
 *
 * Здесь только то, чего не знает платформа: имена осей, подписи состояний и
 * шаблоны объявлений для скринридера. Форматы чисел и дат в локали **не
 * кладутся** — их даёт `Intl` по тегу локали, и держать их тут значило бы
 * поддерживать столько языков, сколько мы успели вписать.
 *
 * Ключи лежат под своим блоком `grCharts`: компонент спрашивает
 * `grCharts.chart.empty`. Английский текст продублирован в компоненте вторым
 * аргументом `t(key, fallback)` — пакет обязан работать и без подключённого
 * адаптера i18n.
 *
 * Наружу отсюда уходят **лоадеры** (`en`, `ru`, `es`): приложение подключает
 * словарь через них, а не сырым JSON. Сам JSON остаётся доступен объектом
 * `grChartsMessages` — он нужен инструментам локализации, а не рантайму.
 */
import en from './locales/en.json'
import es from './locales/es.json'
import ru from './locales/ru.json'

export const grChartsMessages = { en, es, ru } as const

export type GrChartsLocale = keyof typeof grChartsMessages

