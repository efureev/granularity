/** Обводка марки: на пересечении двух контуров она иначе сливается с чужой линией. */
export const radarMarkerHalo = 'var(--gr-chart-radar-marker-halo,var(--gr-bg))'

/** Имя активной оси. Выделяется и в рисунке, и в подписи — двумя разными признаками. */
export const radarActiveLabelFill = 'var(--gr-chart-radar-axis-active,var(--gr-fg))'

