import type { GrChartSize } from '../GrChartFrame/chartFrameStyles'

export type { GrChartSize as GrChartRadarSize }

/**
 * Оформление паутины — токенами через атрибуты SVG.
 *
 * Своих здесь ровно четыре. Сетка, спицы, подписи и активная ось берут токены
 * **рамы** (`--gr-chart-frame-*`): второй цвет сетки на той же странице читался
 * бы как ошибка вёрстки, а активная спица — это буквально вертикаль под
 * активной точкой, только в полярных координатах, и роль у неё та же.
 */

