/**
 * Реестр ИЗВЕСТНЫХ (pre-existing) axe-нарушений по компонентам — «долг доступности»,
 * зафиксированный при внедрении a11y-слоя.
 *
 * Зачем baseline, а не «зелёный любой ценой»: внедрять axe на существующую кодовую
 * базу принято через фиксацию текущего состояния и гейт на *регрессии* — новые
 * нарушения (и любой НОВЫЙ компонент) падают сразу, а накопленный долг виден списком
 * и выжигается со временем (удаляем строки по мере починки). Пустой список для
 * компонента = он обязан быть чистым.
 *
 * Правило `color-contrast` с 2026-07-28 ВКЛЮЧЕНО (ANALYSIS §54) и в baseline не
 * занесено ни для одного компонента: контраст обязан быть чистым везде. Токен
 * `--gr-muted-fg`, из-за которого правило раньше было выключено, исправлен в
 * обеих темах.
 *
 * Долг выжжен 2026-07-28…29 (ANALYSIS §53) с 19 компонентов до двух. Что закрыто:
 *
 *  - `nested-interactive` (было 14 компонентов). Корень — паттерн «элемент с
 *    виджет-ролью + вложенный интерактивный потомок»: роль объявляет потомков
 *    презентационными, поэтому вложенный контрол ломал виджет. `GrRadio`/`GrSegmented`
 *    перешли на `input[type="hidden"]`; у `GrCheckbox` роль сужена до самого контрола
 *    (подпись с её ссылками и кнопками вынесена наружу и связана `aria-labelledby`);
 *    у `GrFileUpload` роль с drop-зоны снята вовсе — доступным контролом стал сам
 *    нативный `<input type="file">`.
 *  - `select-name` (3 компонента). Дефект был не в `GrSelect`, а в демо: подпись
 *    рисовалась отдельным `div`, а нарисованный рядом текст доступным именем не
 *    становится — `GrSelect` берёт id только из `GrFormField`. Все три места
 *    (GrSegmented, GrRadioGroup, GrResponseErrorBanner) переведены на `GrFormField`.
 *  - `button-name` (3 компонента) — контролы без доступного имени: icon-only сегменты
 *    `GrSegmented` (в `GrSegmentedOption` добавлено поле `ariaLabel`), icon-only
 *    кнопка-действие в демо `GrDataTable` и переключатели без подписи в демо `GrList`
 *    (заголовок соседнего `GrListItem` контролу не принадлежит).
 *  - `color-contrast` у `GrFileUpload` — вылез из-под снятой роли: axe не проверяет
 *    содержимое презентационных потомков, и disabled-зона с `opacity` годами
 *    проходила гейт.
 *
 * Что стоит за оставшимися двумя пунктами:
 *  - `label` у `GrInputTag` — нативный контрол без доступного имени.
 *  - `scrollable-region-focusable` у `GrToaster` — скролл-контейнер без доступа с
 *    клавиатуры; мигающий, зависит от того, висит ли тост в момент прогона.
 *
 * Чем проверять, не протух ли список: `A11Y_AUDIT=1` в прогоне `test:a11y` игнорирует
 * baseline и печатает весь долг — обычный гейт про регрессии и на долге молчит.
 *
 * ВНИМАНИЕ: список сознательно НЕ содержит `GrSlider`, `GrAutocomplete`, `GrTabs`,
 * `GrTree`, `GrDropdown`, `GrModal` и др. — они проходят гейт начисто.
 */
export const a11yKnownIssues: Record<string, string[]> = {
  GrInputTag: ['label'],
  GrToaster: ['scrollable-region-focusable'],
}

export function knownIssuesFor(componentName: string): string[] {
  return a11yKnownIssues[componentName] ?? []
}
