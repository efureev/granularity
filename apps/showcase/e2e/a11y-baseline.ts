/**
 * Реестр ИЗВЕСТНЫХ (pre-existing) axe-нарушений по компонентам — «долг доступности».
 *
 * **Список пуст с 2026-07-29: долг выжжен целиком** (был 19 компонентов, ANALYSIS §53).
 * Это не значит, что файл больше не нужен: он остаётся точкой, куда осознанно и с
 * объяснением заносится нарушение, которое почему-то нельзя починить сразу. Пустой
 * список для компонента (т.е. отсутствие записи) = компонент обязан быть чистым, и
 * гейт `a11y.spec.ts` падает на любом serious/critical нарушении.
 *
 * Заносить сюда новое нарушение — крайняя мера и требует согласия владельца:
 * baseline задумывался для фиксации накопленного долга при внедрении axe, а не как
 * место, куда прячут свежие регрессии.
 *
 * Что было выжжено и чем это лечилось (полезно как каталог приёмов):
 *
 *  - `nested-interactive` (14 компонентов). Корень — паттерн «элемент с виджет-ролью
 *    + вложенный интерактивный потомок»: роль объявляет потомков презентационными,
 *    поэтому вложенный контрол ломал виджет. `GrRadio`/`GrSegmented` перешли на
 *    `input[type="hidden"]`; у `GrCheckbox` роль сужена до самого контрола (подпись с
 *    её ссылками и кнопками вынесена наружу и связана `aria-labelledby`); у
 *    `GrFileUpload` роль с drop-зоны снята вовсе — доступным контролом стал сам
 *    нативный `<input type="file">`.
 *  - `select-name` (3 компонента). Дефект был не в `GrSelect`, а в демо: подпись
 *    рисовалась отдельным `div`, а нарисованный рядом текст доступным именем не
 *    становится — `GrSelect` берёт id только из `GrFormField`.
 *  - `button-name` (3 компонента) — контролы без доступного имени: icon-only сегменты
 *    `GrSegmented` (в `GrSegmentedOption` добавлено поле `ariaLabel`), icon-only
 *    кнопка-действие в демо `GrDataTable` и переключатели в демо `GrList` (заголовок
 *    соседнего `GrListItem` контролу не принадлежит).
 *  - `label` у `GrInputTag` — у компонента не было ни `ariaLabel`, ни интеграции с
 *    `GrFormField`, то есть имя нельзя было задать в принципе. Добавлено и то и другое.
 *  - `scrollable-region-focusable` — скроллящиеся блоки без доступа с клавиатуры:
 *    `<pre>` в `CodeBlock` витрины (он же всплывал на странице `GrToaster`) и в демо
 *    нативной формы `GrCheckbox`. Лечится `tabindex="0"`.
 *  - `color-contrast` у `GrFileUpload` — вылез из-под снятой роли: axe не проверяет
 *    содержимое презентационных потомков, и disabled-зона с `opacity` годами
 *    проходила гейт.
 *
 * Правило `color-contrast` включено с 2026-07-28 (ANALYSIS §54): контраст обязан быть
 * чистым везде. Токен `--gr-muted-fg`, из-за которого правило раньше было выключено,
 * исправлен в обеих темах.
 *
 * Чем смотреть долг: `A11Y_AUDIT=1` в прогоне `test:a11y` игнорирует baseline и
 * печатает всё, что нашёл — обычный гейт про регрессии и на записанном долге молчит.
 */
