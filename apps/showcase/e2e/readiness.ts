import type { Page } from '@playwright/test'
import { expect } from '@playwright/test'

/**
 * Страница витрины доехала до своего окончательного вида.
 *
 * Оба сквозных слоя — axe и визуальный — снимают страницу как есть, поэтому
 * обязаны ждать одного и того же. Знание живёт здесь, а не в двух спеках:
 * разойдясь, они начали бы мерить разные страницы под одним адресом.
 */
export async function waitForSettledPreviews(page: Page): Promise<void> {
  // Демо приезжают асинхронными компонентами, а якорь готовности — заголовок
  // секции: он появляется раньше них. Без ожидания axe успевал просканировать
  // пустые рамки превью и объявить страницу чистой, ничего не проверив.
  await expect.poll(async () => page.evaluate(() => [...document.querySelectorAll('[data-example-preview]')]
    .filter(preview => preview.childElementCount === 0)
    .length)).toBe(0)

  /*
   * Непустого превью мало там, где содержимое подменяется после загрузки.
   *
   * `GrCodeEditor` строится за `await import('./codemirror')` в `onMounted`, и
   * до разрешения импорта рисует статический `<pre>` — тот самый первый экран
   * без JS. То есть у одной страницы два разных DOM, и какой из них попадёт
   * под скан, решает то, прогрет ли чанк соседними тестами. Измерено на
   * контрасте плейсхолдера: в полном прогоне из 111 тестов проходило,
   * в изоляции падало 3 раза из 3.
   *
   * Ждём исчезновения заглушки, а не паузой: пауза угадывает. Свой класс
   * заглушки уникален — у `GrCodeBlock`, который остаётся `<pre>` навсегда,
   * он другой (`gr-code-block__line`), поэтому ожидание не зависнет на нём.
   */
  await expect.poll(async () => page.evaluate(
    () => document.querySelectorAll('[data-example-preview] .gr-code-editor__line').length,
  )).toBe(0)
}
