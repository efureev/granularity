import type { Component, VNode } from 'vue'

/**
 * Фикстура компонента — минимальная разметка, поднимающая его в одиночку.
 *
 * Одна фикстура = один адрес = один компонент в разметке. Изоляция здесь не
 * аккуратность, а условие измерения: на общей странице падение одного
 * компонента уносит рендер всей, а расхождение гидрации читается в общей куче
 * и не указывает на виновника.
 *
 * Фикстура не демонстрирует компонент и не покрывает его варианты — для этого
 * есть витрина. Она отвечает на два вопроса: поднимается ли компонент там, где
 * нет `window`, и совпадает ли серверная разметка с первым клиентским рендером.
 */
export interface ComponentFixture {
  /** Имя как в `granular-provider` пакета: по нему сверяется полнота. */
  name: string
  /** Что именно рискованно в этом компоненте на сервере. Попадает в шапку страницы. */
  about: string
  /**
   * Разметка через `h()` — по умолчанию.
   *
   * Пропы взяты минимальные и **детерминированные**: часы, случайность и
   * замеры среды в фикстуре запрещены, иначе сервер и клиент разойдутся по
   * вине стенда, а не компонента.
   */
  render?: () => VNode
  /**
   * Люк для композиций, которые в `h()` перестают читаться: вложенные слоты,
   * связка «родитель + пункты», `v-model` на нескольких уровнях.
   */
  page?: Component
  /**
   * Компонент **обязан** не отдавать содержимое на сервер — так живут закрытые
   * модальные слои и всё, что поднимается только после монтирования.
   *
   * Флаг двусторонний: без него гейт требует непустую разметку, с ним —
   * пустую. Иначе «страница отрисовалась» зеленело бы и там, где на сервер не
   * приехало вообще ничего, а проверка гидрации сравнивала бы две пустоты.
   */
  emptyOnServer?: boolean
}

/** Компонент, который отрисовать в одиночку нельзя, и почему. */
export interface UnrenderableComponent {
  name: string
  reason: string
}
